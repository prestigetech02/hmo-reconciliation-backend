'use strict';

const mongoose = require('mongoose');

const EXCEPTION_CODES = [
  'CHARGE_VARIANCE',      // Invoiced amount differs from expected plan rate
  'MISSING_FROM_INVOICE', // Employee enrolled but not on invoice
  'NOT_ENROLLED',         // On invoice but not in enrolment records
  'DUPLICATE_CHARGE',     // Employee appears more than once on invoice
  'RATE_MISMATCH',        // Plan rate on invoice differs from configured rate
  'PAYMENT_SHORTFALL',    // Payment made is less than invoice total
];

const EXCEPTION_STATUSES = ['open', 'under_review', 'resolved', 'waived'];
const SEVERITIES = ['high', 'medium', 'low'];

const resolutionEventSchema = new mongoose.Schema(
  {
    note: { type: String, required: true },
    action: { type: String, enum: EXCEPTION_STATUSES, required: true },
    recordedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    recordedAt: { type: Date, default: Date.now },
  },
  { _id: false },
);

const sourceReferenceSchema = new mongoose.Schema(
  {
    collection: { type: String, required: true }, // e.g. 'employeerecords'
    recordId: { type: mongoose.Schema.Types.ObjectId, required: true },
    field: { type: String }, // e.g. 'invoicedAmount'
  },
  { _id: false },
);

const exceptionSchema = new mongoose.Schema(
  {
    organizationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Organization',
      required: true,
      index: true,
    },
    reconciliationRunId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'ReconciliationRun',
      required: true,
      index: true,
    },
    hmoId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'HMO',
      required: true,
    },
    billingPeriod: {
      type: String,
      required: true,
    },
    code: {
      type: String,
      enum: EXCEPTION_CODES,
      required: true,
    },
    severity: {
      type: String,
      enum: SEVERITIES,
      required: true,
    },
    status: {
      type: String,
      enum: EXCEPTION_STATUSES,
      default: 'open',
    },

    // ─── Employee Context ────────────────────────────────────────────────────
    staffId: { type: String, required: true },
    employeeName: { type: String, default: null },

    // ─── Financial Detail ────────────────────────────────────────────────────
    invoicedAmount: { type: String, default: null },
    expectedAmount: { type: String, default: null },
    variance: { type: String, default: null },
    currency: { type: String, default: 'NGN' },

    /**
     * Human-readable explanation generated by the engine.
     * May be templated or LLM-generated — never a fraud accusation.
     */
    explanation: { type: String, required: true },

    /**
     * Exact pointers back to the source records that produced this exception.
     * Required for finance officers to investigate without guessing.
     */
    sourceReferences: { type: [sourceReferenceSchema], default: [] },

    // ─── Resolution Trail ────────────────────────────────────────────────────
    resolutionHistory: { type: [resolutionEventSchema], default: [] },
    resolvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
    resolvedAt: { type: Date, default: null },
  },
  {
    timestamps: true,
  },
);

// ─── Indexes ──────────────────────────────────────────────────────────────────
exceptionSchema.index({ organizationId: 1, status: 1, createdAt: -1 });
exceptionSchema.index({ organizationId: 1, staffId: 1 });
exceptionSchema.index({ organizationId: 1, hmoId: 1, billingPeriod: 1 });

const Exception = mongoose.model('Exception', exceptionSchema);

module.exports = { Exception, EXCEPTION_CODES, EXCEPTION_STATUSES, SEVERITIES };
